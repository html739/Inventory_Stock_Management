CREATE OR REPLACE PROCEDURE ADD_PRODUCT (
    P_ID       IN NUMBER,
    P_NAME     IN VARCHAR2,
    P_CATEGORY IN VARCHAR2,
    P_QUANTITY IN NUMBER,
    P_PRICE    IN NUMBER
)
AS
BEGIN
    INSERT INTO PRODUCTS (
        PRODUCT_ID,
        PRODUCT_NAME,
        CATEGORY,
        QUANTITY,
        PRICE
    )
    VALUES (
        P_ID,
        P_NAME,
        P_CATEGORY,
        P_QUANTITY,
        P_PRICE
    );

    COMMIT;
END;
