CREATE OR REPLACE PROCEDURE STOCK_IN (
    P_ID IN NUMBER,
    P_QTY IN NUMBER
)
AS
BEGIN
    UPDATE PRODUCTS
    SET QUANTITY = QUANTITY + P_QTY
    WHERE PRODUCT_ID = P_ID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Product not found');
    END IF;

    COMMIT;
END;
/

BEGIN
    STOCK_IN(1, 5);
END;
