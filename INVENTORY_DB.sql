CREATE OR REPLACE PROCEDURE STOCK_OUT (
    P_ID IN NUMBER,
    P_QTY IN NUMBER
)
AS
BEGIN
    IF P_QTY <= 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Quantity must be positive');
    END IF;

    UPDATE PRODUCTS
    SET QUANTITY = QUANTITY - P_QTY
    WHERE PRODUCT_ID = P_ID
      AND QUANTITY >= P_QTY;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20003,
            'Product not found or insufficient stock'
        );
    END IF;

    COMMIT;
END;
/

CREATE OR REPLACE PROCEDURE LOW_STOCK_REPORT
AS
BEGIN
    FOR P IN (
        SELECT PRODUCT_ID, PRODUCT_NAME, QUANTITY
        FROM PRODUCTS
        WHERE QUANTITY <= 5
        ORDER BY QUANTITY
    )
    LOOP
        DBMS_OUTPUT.PUT_LINE(
            'ID: ' || P.PRODUCT_ID ||
            ' | Product: ' || P.PRODUCT_NAME ||
            ' | Quantity: ' || P.QUANTITY
        );
    END LOOP;
END;
/

CREATE TABLE AUDIT_LOG (
    AUDIT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER,
    OLD_QUANTITY NUMBER,
    NEW_QUANTITY NUMBER,
    CHANGE_DATE DATE DEFAULT SYSDATE
);

CREATE OR REPLACE TRIGGER STOCK_AUDIT_TRIGGER
AFTER UPDATE OF QUANTITY ON PRODUCTS
FOR EACH ROW
BEGIN
    IF :OLD.QUANTITY <> :NEW.QUANTITY THEN
        INSERT INTO AUDIT_LOG (
            PRODUCT_ID,
            OLD_QUANTITY,
            NEW_QUANTITY,
            CHANGE_DATE
        )
        VALUES (
            :OLD.PRODUCT_ID,
            :OLD.QUANTITY,
            :NEW.QUANTITY,
            SYSDATE
        );
    END IF;
END;
